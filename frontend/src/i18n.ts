export function translateRecordValue(
  language: Language,
  group: keyof Pick<
    typeof dictionary.en,
    'modeNames' | 'modePurposes' | 'sectionLabels' | 'itemLabels' | 'fieldLabels' | 'boardColumns'
  >,
  id: string,
  fallback: string,
) {
  const values = dictionary[language][group] as Record<string, string>;

  return values[id] ?? fallback;
}

export function translateDashboardCard(
  language: Language,
  modeId: string,
  card: DashboardCardConfig,
): DashboardCardConfig {
  const dashboardCardTranslations = dictionary[language].dashboardCards as DashboardCardTranslationGroup;
  const cardTranslation = dashboardCardTranslations[modeId]?.[card.id];

  if (!cardTranslation) {
    return card;
  }

  return {
    ...card,
    kicker: cardTranslation.kicker ?? card.kicker,
    title: cardTranslation.title ?? card.title,
    pill: cardTranslation.pill ?? card.pill,
    rows: card.rows.map((row, index) => {
      const rowTranslation = cardTranslation.rows?.[row.id ?? String(index)];

      if (!rowTranslation) {
        return row;
      }

      return {
        ...row,
        label: rowTranslation.label ?? row.label,
        value: rowTranslation.value ?? row.value,
        description: rowTranslation.description ?? row.description,
      };
    }),
  };
}

export function getHolidayForDate(language: Language, date: string) {
  return holidaysByLanguage[language].find((holiday) => holiday.date === date);
}

export function formatMonthHeading(language: Language, monthLabel: string) {
  const [monthName, rawYear] = monthLabel.split(' ');
  const monthIndex = dictionary.en.monthNames.findIndex((name) => name === monthName);
  const year = rawYear ?? '';

  if (monthIndex < 0) {
    return { primary: monthLabel, secondary: '' };
  }

  if (language === 'ko') {
    return {
      primary: dictionary.ko.monthNames[monthIndex],
      secondary: year,
    };
  }

  return {
    primary: `${dictionary.en.monthNames[monthIndex]},`,
    secondary: year,
  };
}

